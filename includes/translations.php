/**
 * Return the translated string for the current session language.
 *
 * @param string $key  Translation key
 * @param string|null $forceLang  Override language ('en'|'mm')
 * @return string
 */
function t(string $key, ?string $forceLang = null): string
{
    $lang = $forceLang ?? ($_SESSION['language'] ?? 'en');
    $map  = $GLOBALS['_wi_translations'][$key] ?? null;
    if ($map === null) return $key;
    return $map[$lang] ?? $map['en'] ?? $key;
}
